/**
 * Enum representing different exposure zones for working sets.
 */
export enum ExposureZone {
  /**
   * Comfortable, restorative, low threat
   */
  Green = 'GREEN',

  /**
   * Productive adaptation zone
   */
  Blue = 'BLUE',

  /**
   * High-intensity but controlled
   */
  Yellow = 'YELLOW',

  /**
   * Panic/guarding/unsafe compensation
   */
  Red = 'RED',
}
